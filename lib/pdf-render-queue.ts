/**
 * Очередь отрисовок по страницам документа.
 *
 * Документы переиспользуются из общего кеша (см. pdf-doc-cache.ts), поэтому
 * doc.getPage(n) отдаёт один и тот же объект страницы всем, кто её рисует.
 * Внутри pdf.js у страницы общее состояние разбора: если одну отрисовку
 * отменить, пока рядом идёт вторая, у второй обрывается поток команд рисования —
 * но её промис при этом завершается успешно. Наружу это выглядит как страница,
 * у которой отрисован только верх, а низ пустой, и сама она уже не исправится.
 *
 * Эффекты отрисовки перезапускаются при любом изменении размеров (поворот
 * планшета, появление плашки кеширования, изменение ширины контейнера), так что
 * отмена и немедленный старт новой отрисовки той же страницы — обычное дело.
 *
 * Ключ — документ и номер страницы: параллельно разные страницы рисуются
 * по-прежнему свободно, ждут только отрисовки одной и той же.
 */
/**
 * Дорисована ли страница до низа.
 *
 * Перед отрисовкой холст заливается непрозрачным белым. Если рисование
 * оборвалось на середине или память под холст выделилась не полностью,
 * нижние строки пикселей остаются прозрачными — по ним это и видно.
 * Проверяется одна строка, так что стоит это доли миллисекунды.
 */
export function isBottomDrawn(canvas: HTMLCanvasElement): boolean {
  if (!canvas.width || !canvas.height) return false;
  try {
    const row = canvas
      .getContext("2d")!
      .getImageData(0, canvas.height - 1, canvas.width, 1).data;
    for (let i = 3; i < row.length; i += 4) {
      if (row[i] !== 0) return true;
    }
    return false;
  } catch {
    // Прочитать не удалось — считаем страницу годной, иначе рискуем
    // зациклиться на перерисовке и не показать вообще ничего
    return true;
  }
}

const queues = new Map<string, Promise<unknown>>();

export function queuePageRender<T>(
  key: string,
  task: () => Promise<T>,
): Promise<T> {
  const previous = queues.get(key) ?? Promise.resolve();
  // Отменённая отрисовка завершается отказом — следующая всё равно должна
  // дождаться её и начать работу, поэтому обработчик один на оба исхода
  const next = previous.then(task, task);
  queues.set(
    key,
    next.catch(() => {}),
  );
  return next;
}
