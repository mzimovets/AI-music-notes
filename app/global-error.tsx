"use client";

import { useEffect, useState } from "react";

/**
 * Экран на случай, когда приложение не смогло запуститься.
 *
 * Ловит ровно тот случай, который наблюдали вживую: приложение обновилось,
 * страница пришла из кеша, а её файлы оформления и кода — ещё нет, и связи
 * тоже нет. Раньше это давало голый текст и системное сообщение об ошибке;
 * теперь — понятный экран, который сам пытается восстановиться.
 *
 * Речь не об офлайне как таковом: приложение обязано открываться и из кеша,
 * и с платы, и из интернета. Проблема именно в неполной установке, поэтому
 * и текст об этом, а не «нет интернета».
 */
export default function GlobalError({ reset }: { error: Error; reset: () => void }) {
  const [retrying, setRetrying] = useState(false);

  useEffect(() => {
    // Как только связь появляется — перезагружаемся сами: файлы докачаются
    // с того источника, который оказался рядом, будь то плата или интернет
    const onOnline = () => window.location.reload();
    window.addEventListener("online", onOnline);
    return () => window.removeEventListener("online", onOnline);
  }, []);

  /**
   * Повтор с нарастающей силой.
   *
   * Простая перезагрузка тут не спасала: страницу отдаёт тот же сервис-воркер,
   * который и привёл к беде, — после обновления платы он держит в кеше файлы
   * сборки со старыми именами. Человек жал «Попробовать снова» по кругу, и
   * помогало только закрыть приложение целиком, потому что при новом запуске
   * воркер успевает обновиться.
   *
   * Поэтому сначала обновляем воркер, а если и это не помогло — сбрасываем его
   * вместе с кешем. Сброс делаем только вторым заходом: он стирает скачанные
   * ноты, и они закачаются заново, так что зря к нему прибегать не стоит.
   */
  const retry = async () => {
    setRetrying(true);

    try {
      const attempts = Number(sessionStorage.getItem("startupRetries") || 0);
      sessionStorage.setItem("startupRetries", String(attempts + 1));

      const registration = await navigator.serviceWorker?.getRegistration();
      if (attempts === 0) {
        await registration?.update();
      } else {
        await registration?.unregister();
        if (window.caches) {
          const keys = await caches.keys();
          await Promise.all(keys.map((key) => caches.delete(key)));
        }
      }
    } catch {}

    window.location.reload();
  };

  return (
    <html lang="ru">
      <body
        style={{
          margin: 0,
          minHeight: "100vh",
          background: "#F7F4F1",
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
          padding: 24,
          fontFamily: '"Roboto Slab", Georgia, serif',
          color: "#5A4636",
          textAlign: "center",
        }}
      >
        <div style={{ maxWidth: 420 }}>
          {/* Рисунок встроен, а не подгружается файлом: этот экран показывается
              как раз тогда, когда файлы не грузятся, и картинка выходила битой —
              вместо спутника был знак вопроса. Аварийная страница не должна
              зависеть ни от сети, ни от кеша */}
          <svg
            width={96}
            height={96}
            viewBox="0 0 24 24"
            fill="none"
            xmlns="http://www.w3.org/2000/svg"
            style={{ opacity: 0.55, marginBottom: 24 }}
            aria-hidden="true"
          >
            <path
              fillRule="evenodd"
              clipRule="evenodd"
              d="M12.6291 2.92377L1.6359 9.03126C1.27381 9.23242 1.14336 9.68902 1.34452 10.0511C1.54569 10.4132 2.00229 10.5436 2.36438 10.3425L11.0499 5.5171C10.5132 7.32327 10.8481 9.33324 12.0545 10.8851L4.46981 18.4697C4.17691 18.7626 4.17691 19.2374 4.4698 19.5303C4.7627 19.8232 5.23757 19.8232 5.53046 19.5303L13.1152 11.9457C14.667 13.152 16.6769 13.4868 18.4831 12.9502L13.6577 21.6358C13.4566 21.9979 13.587 22.4545 13.9491 22.6556C14.3112 22.8568 14.7678 22.7263 14.969 22.3642L21.0764 11.3709C23.3331 9.03243 23.3078 5.30714 21.0004 2.99975C18.693 0.692357 14.9677 0.667032 12.6291 2.92377ZM20.2732 10.0152C21.6788 8.25856 21.5676 5.6883 19.9397 4.06041C18.3118 2.43252 15.7415 2.32135 13.9849 3.72687C14.0696 3.89872 14.1859 4.11732 14.3409 4.37566C14.772 5.09432 15.504 6.12295 16.6907 7.30957C17.8773 8.49619 18.9059 9.22816 19.6245 9.65927C19.8828 9.81424 20.1014 9.93051 20.2732 10.0152ZM19.0646 11.0697C18.9966 11.0307 18.9259 10.9894 18.8529 10.9456C18.1501 10.524 17.2231 9.87143 16.1698 8.89115L14.1871 10.8738C15.6345 11.9031 17.557 11.9684 19.0646 11.0697ZM13.1264 9.81314C12.097 8.36572 12.0316 6.44317 12.9304 4.93544C12.9694 5.00355 13.0107 5.07423 13.0546 5.14735C13.4762 5.85016 14.1288 6.77721 15.1091 7.8305L13.1264 9.81314Z"
              fill="#7D5E42"
            />
          </svg>

          <h1 style={{ fontSize: 22, fontWeight: 700, margin: "0 0 12px" }}>
            Приложение ещё не загрузилось полностью
          </h1>

          <p style={{ fontSize: 16, lineHeight: 1.5, margin: "0 0 8px", color: "#7D5E42" }}>
            Часть файлов не успела сохраниться на устройство, а связи сейчас нет.
          </p>

          <p style={{ fontSize: 15, lineHeight: 1.5, margin: "0 0 28px", color: "#9A8878" }}>
            Подключитесь к Wi-Fi платы или к интернету — загрузка продолжится
            сама с того места, где остановилась.
          </p>

          <button
            onClick={retry}
            disabled={retrying}
            style={{
              appearance: "none",
              border: "none",
              borderRadius: 14,
              padding: "14px 28px",
              fontSize: 16,
              fontFamily: "inherit",
              color: "#fff",
              background: "linear-gradient(to right, #BD9673, #7D5E42)",
              boxShadow: "0 4px 12px rgba(0,0,0,0.18)",
              cursor: retrying ? "default" : "pointer",
              opacity: retrying ? 0.6 : 1,
            }}
          >
            {retrying ? "Загружаю…" : "Попробовать снова"}
          </button>
        </div>
      </body>
    </html>
  );
}
